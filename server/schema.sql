-- Neon Arena leaderboard (Cloudflare D1 / SQLite)

CREATE TABLE IF NOT EXISTS players (
  id TEXT PRIMARY KEY,              -- random id generated by the game
  secret_hash TEXT NOT NULL,        -- SHA-256 of the per-device secret
  name TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

-- One token per started run; a run can only be submitted with its own token, once.
CREATE TABLE IF NOT EXISTS run_tokens (
  token TEXT PRIMARY KEY,
  player_id TEXT NOT NULL,
  ip_hash TEXT NOT NULL,
  started_at INTEGER NOT NULL,      -- ms, server clock
  used INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_tokens_player ON run_tokens(player_id, started_at);
CREATE INDEX IF NOT EXISTS idx_tokens_ip ON run_tokens(ip_hash, started_at);

CREATE TABLE IF NOT EXISTS runs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  season INTEGER NOT NULL,
  player_id TEXT NOT NULL,
  platform TEXT NOT NULL,           -- pc / phone / tablet
  mode TEXT NOT NULL,               -- kbm / twin / hybrid / auto
  score INTEGER NOT NULL,
  wave INTEGER NOT NULL,
  kills INTEGER NOT NULL,
  duration INTEGER NOT NULL,        -- seconds alive
  weapon TEXT NOT NULL,
  version TEXT NOT NULL,
  day TEXT NOT NULL,                -- YYYY-MM-DD in UTC+8
  week TEXT NOT NULL,               -- YYYY-MM-DD of that week's Monday, UTC+8
  created_at INTEGER NOT NULL,
  flagged INTEGER NOT NULL DEFAULT 0  -- failed plausibility checks; hidden from boards
);
CREATE INDEX IF NOT EXISTS idx_runs_board ON runs(season, platform, mode, flagged, score DESC);
CREATE INDEX IF NOT EXISTS idx_runs_week ON runs(season, platform, mode, week, score DESC);
CREATE INDEX IF NOT EXISTS idx_runs_day ON runs(season, platform, mode, day, score DESC);
CREATE INDEX IF NOT EXISTS idx_runs_player ON runs(player_id);

-- Best run per player per board and period, kept up to date on submit so board reads stay
-- small (D1 bills rows read). period: all / week / day; period_key: "all" or the date key.
CREATE TABLE IF NOT EXISTS bests (
  season INTEGER NOT NULL,
  platform TEXT NOT NULL,
  mode TEXT NOT NULL,
  period TEXT NOT NULL,
  period_key TEXT NOT NULL,
  player_id TEXT NOT NULL,
  score INTEGER NOT NULL,
  wave INTEGER NOT NULL,
  weapon TEXT NOT NULL,
  duration INTEGER NOT NULL,
  created_at INTEGER NOT NULL,
  PRIMARY KEY (season, platform, mode, period, period_key, player_id)
);
CREATE INDEX IF NOT EXISTS idx_bests_rank ON bests(season, platform, mode, period, period_key, score DESC);
CREATE INDEX IF NOT EXISTS idx_bests_player ON bests(player_id);

-- Co-op room creation rate limit (per IP, last hour).
CREATE TABLE IF NOT EXISTS room_creates (
  ip TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_room_creates ON room_creates (ip, created_at);
